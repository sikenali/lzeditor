type CategoryId = typeof EMOJI_CATEGORIES[number]['id']

export const EmojiDialog: React.FC<EmojiDialogProps> = ({ onClose, onInsert }) => {
  const [activeCat, setActiveCat] = useState<CategoryId>('smiley')
  const [search, setSearch] = useState('')
  const searchRef = useRef<HTMLInputElement>(null)

  useEffect(() => {
    searchRef.current?.focus()
  }, [])

  const emojis = EMOJI_DATA[activeCat] ?? []
  const filtered = search ? emojis.filter(e => e.includes(search)) : emojis

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="export-dialog" style={{ width: 520 }} onClick={e => e.stopPropagation()}>
        <div className="export-header">
          <div className="export-title">
            <span className="remix export-icon ri-emotion-line"></span>
            <div>
              <div className="export-title-text">插入表情</div>
              <div className="export-title-desc">{EMOJI_CATEGORIES.find(c => c.id === activeCat)?.label || ''} · {filtered.length} 个</div>
            </div>
          </div>
          <button className="settings-close-btn" onClick={onClose}>
            <span className="remix ri-close-line"></span>
          </button>
        </div>

        <div className="export-body">
          {/* Search */}
          <div style={{ position: 'relative', marginBottom: 12 }}>
            <span className="remix ri-search-line" style={{ position: 'absolute', left: 10, top: '50%', transform: 'translateY(-50%)', fontSize: 14, color: 'var(--text-muted)', pointerEvents: 'none' }}></span>
            <input
              ref={searchRef}
              value={search}
              onChange={e => setSearch(e.target.value)}
              placeholder="搜索表情..."
              className="emoji-search-input"
            />
            {search && (
              <button onClick={() => setSearch('')} className="emoji-search-clear" type="button">
                <span className="remix ri-close-line"></span>
              </button>
            )}
          </div>

          {/* Category tabs */}
          <div className="emoji-tabs">
            {EMOJI_CATEGORIES.map(cat => (
              <button
                key={cat.id}
                className={`emoji-tab ${activeCat === cat.id ? 'active' : ''}`}
                onClick={() => { setActiveCat(cat.id as CategoryId); setSearch('') }}
                type="button"
              >
                <span className="emoji-tab-emoji">{cat.icon}</span>
                <span>{cat.label}</span>
              </button>
            ))}
          </div>

          {/* Grid */}
          <div className="emoji-grid">
            {filtered.length === 0 ? (
              <div className="emoji-empty">没有找到匹配的内容</div>
            ) : filtered.map((emoji, i) => (
              <button
                key={i}
                className="emoji-item"
                onClick={() => { onInsert(emoji); onClose() }}
                title={emoji}
                type="button"
              >
                {emoji}
              </button>
            ))}
          </div>
        </div>

        <div className="export-footer">
          <div className="export-hint">
            <span className="remix ri-information-line"></span>
            <span>点击表情插入到光标位置</span>
          </div>
          <div className="export-actions">
            <button className="settings-cancel-btn" onClick={onClose} type="button">关闭</button>
          </div>
        </div>
      </div>
    </div>
  )
}
